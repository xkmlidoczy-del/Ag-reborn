package cn.academy.port.client;

import cn.academy.port.VisualTier;
import cn.academy.port.client.RailThunderArrayGeometry.Point;
import cn.academy.port.client.RailThunderArrayGrandGeometry.Quad;
import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.blaze3d.vertex.ByteBufferBuilder;
import com.mojang.blaze3d.vertex.VertexConsumer;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.client.event.RenderLevelStageEvent;
import org.joml.Matrix4f;

/**
 * Renderer for the per-skill motifs. The motifs use their own material set (generated by {@code scripts/generate-motif-textures.py}:
 * turbulent plasma, ragged lightning, hexagon cells, ground cracks, smoke, vortex, circuit traces, coordinate lattice...), drawn as
 * camera-facing ribbons, camera-facing sprites and free-standing plates, additive except for smoke. Purely cosmetic: it reads nothing
 * from the game and writes nothing to it.
 */
final class MotifRenderer {
    enum Tex {
        BLOOM("bloom", true), CHEVRON("chevron", true), CIRCUIT("circuit", true), CRACK("crack", true), STREAK("energy_streak", true), FLARE("flare", true),
        HEX("hex_cells", true), LATTICE("lattice", true), LIGHTNING("lightning", true), PLASMA("plasma_orb", true), RIFT("rift", true), SCAN("scan", true),
        SHARD("shard", true), RING("shock_ring", true), SMOKE("smoke", false), SPARK("spark", true), SPARKLE("sparkle", true), VORTEX("vortex", true),
        LINE("soft_line", true);
        final ResourceLocation location;
        final boolean additive;
        Tex(String name, boolean additive) { this.location = ResourceLocation.fromNamespaceAndPath("academy", "textures/vfx3/" + name + ".png"); this.additive = additive; }
    }

    /** A flat strip from {@code a} to {@code b}, always turned to face the camera; u runs {@code u0}..{@code u1} along it. */
    record Ribbon(Point a, Point b, double half, int rgb, int alpha, Tex tex, double u0, double u1) {}
    /** A camera-facing square of half-size {@code r}, stretched along the screen horizontal by {@code stretch}. */
    record Sprite(Point c, double r, int rgb, int alpha, Tex tex, double roll, double stretch) {}
    /** A free-standing plate spanning {@code c +- u +- v}; texture upright along {@code v}. {@code blend}: alpha-blended instead of additive, so it keeps its own colour in daylight. */
    record Plate(Point c, Point u, Point v, int rgb, int alpha, Tex tex, boolean blend) {
        Plate(Point c, Point u, Point v, int rgb, int alpha, Tex tex) { this(c, u, v, rgb, alpha, tex, false); }
    }

    static final class Prims {
        final List<Ribbon> ribbons = new ArrayList<>();
        final List<Sprite> sprites = new ArrayList<>();
        final List<Plate> plates = new ArrayList<>();
        boolean isEmpty() { return ribbons.isEmpty() && sprites.isEmpty() && plates.isEmpty(); }
        void addAll(Prims o) { ribbons.addAll(o.ribbons); sprites.addAll(o.sprites); plates.addAll(o.plates); }
    }

    private static MultiBufferSource.BufferSource buffers;
    private static final boolean DEBUG = Boolean.getBoolean("aca.motif.debug");
    private static final org.slf4j.Logger LOGGER = com.mojang.logging.LogUtils.getLogger();
    private static final double NEAR = .15, FAR = 160;
    private static final int BLEND = 100;   // texture index offset that marks an alpha-blended quad

    private MotifRenderer() {}

    static void render(RenderLevelStageEvent event, Prims prims, VisualTier tier, int maxQuads) {
        if (prims == null || prims.isEmpty() || tier == null || !tier.enhanced()) return;
        if (!RailThunderArrayGrandMaterial.kitReady()) { if (DEBUG) LOGGER.info("MOTIF render skipped: kit not ready"); return; }
        var cam = event.getCamera();
        var l = cam.getLookVector(); var u = cam.getUpVector(); var c = cam.getPosition();
        List<Quad> quads = project(prims, new Point(c.x, c.y, c.z), new Point(l.x(), l.y(), l.z()), new Point(u.x(), u.y(), u.z()), maxQuads);
        if (DEBUG) LOGGER.info("MOTIF render prims={}/{}/{} quads={}", prims.ribbons.size(), prims.sprites.size(), prims.plates.size(), quads.size());
        if (quads.isEmpty()) return;
        if (buffers == null) buffers = MultiBufferSource.immediate(new ByteBufferBuilder(262144));
        var poses = event.getPoseStack(); var modelView = RenderSystem.getModelViewStack();
        float[] color = RenderSystem.getShaderColor().clone();
        modelView.pushMatrix(); poses.pushPose();
        try {
            RenderSystem.setShaderColor(1, 1, 1, 1); modelView.set(event.getModelViewMatrix()); RenderSystem.applyModelViewMatrix();
            submit(buffers, poses.last().pose(), quads);
        } finally {
            try { buffers.endBatch(); } finally {
                poses.popPose(); modelView.popMatrix(); RenderSystem.applyModelViewMatrix();
                RenderSystem.setShaderColor(color[0], color[1], color[2], color[3]);
            }
        }
    }

    // ---- projection: every corner is relative to the camera, as the shared kit expects -------------------------------------------

    static List<Quad> project(Prims prims, Point cam, Point look, Point up, int maxQuads) {
        var out = new ArrayList<Quad>();
        Point f = MotifKit.norm(look), side = MotifKit.norm(f.cross(up)), cu = side.cross(f);
        for (Plate p : prims.plates) {
            Point rel = p.c().minus(cam);
            if (!ok(rel, f, p.u().length() + p.v().length())) continue;
            out.add(new Quad(rel.minus(p.u()).plus(p.v()), rel.minus(p.u()).minus(p.v()), rel.plus(p.u()).minus(p.v()), rel.plus(p.u()).plus(p.v()), 0f, 1f, p.rgb(), p.alpha(), p.tex().ordinal() + (p.blend() ? BLEND : 0)));
        }
        for (Ribbon r : prims.ribbons) {
            Point a = r.a().minus(cam), b = r.b().minus(cam), mid = a.lerp(b, .5), d = b.minus(a);
            if (!ok(mid, f, d.length() * .5 + r.half())) continue;
            Point n = d.cross(mid);
            double nl = n.length();
            if (nl < 1e-9) continue;
            n = n.scale(r.half() / nl);
            out.add(new Quad(a.plus(n), a.minus(n), b.minus(n), b.plus(n), (float) r.u0(), (float) r.u1(), r.rgb(), r.alpha(), r.tex().ordinal()));
        }
        for (Sprite s : prims.sprites) {
            Point rel = s.c().minus(cam);
            if (!ok(rel, f, s.r())) continue;
            double co = Math.cos(s.roll()), si = Math.sin(s.roll());
            Point right = side.scale(co).plus(cu.scale(si)).scale(s.r() * s.stretch()), upward = cu.scale(co).minus(side.scale(si)).scale(s.r());
            out.add(new Quad(rel.minus(right).plus(upward), rel.minus(right).minus(upward), rel.plus(right).minus(upward), rel.plus(right).plus(upward), 0f, 1f, s.rgb(), s.alpha(), s.tex().ordinal()));
        }
        return out.size() <= maxQuads ? out : List.copyOf(out.subList(0, maxQuads));
    }

    private static boolean ok(Point rel, Point forward, double extent) {
        if (!rel.finite()) return false;
        double depth = rel.dot(forward);
        return depth > NEAR - extent * .2 && rel.length() < FAR;
    }

    // ---- submission --------------------------------------------------------------------------------------------------------

    private static void submit(MultiBufferSource buf, Matrix4f matrix, List<Quad> quads) {
        Tex[] all = Tex.values();
        for (Quad q : quads) {
            boolean blend = q.texture() >= BLEND;
            Tex t = all[q.texture() % BLEND];
            RenderType type = t.additive && !blend ? VisualAdditiveMaterial.additive(t.location) : ClassicRenderTypes.world(t.location);
            VertexConsumer out = buf.getBuffer(type);
            vertex(out, matrix, q.a(), q.minV(), 0f, q.rgb(), q.alpha());
            vertex(out, matrix, q.b(), q.minV(), 1f, q.rgb(), q.alpha());
            vertex(out, matrix, q.c(), q.maxV(), 1f, q.rgb(), q.alpha());
            vertex(out, matrix, q.d(), q.maxV(), 0f, q.rgb(), q.alpha());
        }
    }

    private static void vertex(VertexConsumer out, Matrix4f m, Point p, float u, float v, int rgb, int alpha) {
        out.addVertex(m, (float) p.x(), (float) p.y(), (float) p.z()).setUv(u, v).setColor((rgb >>> 16) & 255, (rgb >>> 8) & 255, rgb & 255, alpha);
    }
}
